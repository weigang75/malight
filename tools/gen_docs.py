def gather_modules():
    """收集所有要生成文档的模块。"""
    modules = []
    for root, dirs, names in os.walk(os.path.join(ROOT, "malight")):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for n in sorted(names):
            if not n.endswith(".py"):
                continue
            path = os.path.join(root, n)
            key = rel(ROOT, path)
            if n in SKIP_NAMES or key in SKIP_NAMES:
                continue
            modules.append(path)
    return sorted(modules)


def build_context(path, sibling_names):
    src = read_src(path)
    tree = ast.parse(src)
    doc = ast.get_docstring(tree)
    title, english, body = module_doc_parts(doc)
    name = os.path.basename(path)[:-3]
    doc_dir = os.path.dirname(path)
    up = os.path.relpath(ROOT, doc_dir).replace(os.sep, "/")
    functions, classes = collect_module(tree)
    siblings = [s for s in sibling_names if s != name]
    key = rel(ROOT, path)
    return {
        "src": key,
        "name": name,
        "title": md_text(title) or name,
        "en_title": md_text(english),
        "english": md_text(english),
        "body": rst_to_md(body),
        # 英文正文来自 tools/body_en.py（中文正文一变，那边的指纹检查就会报过期）
        "body_en": body_en_mod.BODY_EN.get(key, ""),
        "api": (functions, classes),
        "example": extract_example(src),
        "readme": up + "/README.md",
        "readme_en": up + "/README.en.md",
        "siblings": siblings,
    }


def write_index(modules_info):
    """重建 README 里两个标记之间的模块索引表。"""
    groups = {}
    for doc_base, name, title, en_title in modules_info:
        parts = doc_base.split("/")
        group = "/".join(parts[:2]) if len(parts) > 2 else "malight"
        groups.setdefault(group, []).append((name, doc_base, title, en_title))

    touches = 0
    for readme, lang in (("README.md", "cn"), ("README.en.md", "en")):
        path = os.path.join(ROOT, readme)
        if not os.path.isfile(path):
            continue
        text = read(path)
        if INDEX_START not in text or INDEX_END not in text:
            continue
        blocks = []
        for group in sorted(groups):
            rows = groups[group]
            if group == "malight":
                blocks.append("### malight（顶层模块）"
                              if lang == "cn" else "### malight (top-level)")
            else:
                blocks.append("### {}".format(group))
            blocks.append("")
            blocks.append("| 模块 / Module | 说明 / Description |" if lang == "cn"
                          else "| Module | Description |")
            blocks.append("|---|---|")
            for name, doc_base, title, en_title in rows:
                link = "{}.zh.md".format(doc_base) if lang == "cn" \
                    else "{}.en.md".format(doc_base)
                desc = title if lang == "cn" else (en_title or title)
                blocks.append("| [{}]({}) | {} |".format(name, link, desc))
            blocks.append("")
        new = INDEX_START + "\n" + "\n".join(blocks).rstrip() + "\n" + INDEX_END
        text = re.sub(re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END),
                      lambda _m: new, text, flags=re.S)
        write(path, text)
        touches += 1
    return touches


def main(argv):
    check = "--check" in argv
    filters = [a for a in argv if not a.startswith("--")]
    modules = gather_modules()
    by_dir = {}
    for path in modules:
        by_dir.setdefault(os.path.dirname(path), []).append(
            os.path.basename(path)[:-3])

    written, info, dirty = 0, [], []
    for path in modules:
        name = os.path.basename(path)[:-3]
        if filters and not any(f in name or f in path for f in filters):
            continue
        ctx = build_context(path, sorted(by_dir[os.path.dirname(path)]))
        for lang, suffix in (("cn", ".zh.md"), ("en", ".en.md")):
            target = os.path.join(os.path.dirname(path), name + suffix)
            text = render_page(ctx, lang)
            if lang == "en":
                bad = purity_problems(text)
                if bad:
                    dirty.append((rel(ROOT, target), bad))
            if check:
                old = read(target) if os.path.isfile(target) else None
                if old != text:
                    print("过期 / STALE: %s" % rel(ROOT, target))
                    written += 1
            else:
                write(target, text)
                written += 1
        info.append((ctx["src"][:-3], name, ctx["title"], ctx["en_title"]))

    if not check:
        write_index(info)

    for target, bad in dirty:
        print("英文页出现中文 / CJK in English page: %s" % target)
        for no, line in bad[:5]:
            print("    L%-4d %s" % (no, line))
    if dirty:
        print("（英文页只允许语言开关里的 [简体中文]；正文译文放 tools/body_en.py，"
              "示例注释与文案放 tools/code_en.py）")

    print("%s %d 个文档" % ("需重新生成" if check else "已生成", written))
    return 1 if ((check and written) or dirty) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
