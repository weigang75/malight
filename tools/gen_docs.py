import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import bipair                                              # noqa: E402
import body_en as body_en_mod                              # noqa: E402
from gen_previews import PREVIEWS, preview_link            # noqa: E402

CN = re.compile(r"[\u4e00-\u9fff]")
#: 英文页唯一允许出现中文的地方：语言开关的链接文字
SWITCH = re.compile(r"\[\u7b80\u4f53\u4e2d\u6587\]")

#: 不生成文档的文件（包的 __init__.py 只做再导出，页面会是空壳）
SKIP_NAMES = {"__init__.py"}

INDEX_START = "<!-- DOCS-INDEX:START -->"
INDEX_END = "<!-- DOCS-INDEX:END -->"

BANNER_CN = ("<!-- 本文件由 tools/gen_docs.py 从源码自动生成，请勿手改。\n"
             "     要改内容请改同目录的 {src} 里的文档字符串，然后重跑生成器。 -->")
BANNER_EN = ("<!-- Generated by tools/gen_docs.py from the source docstrings.\n"
             "     Do not edit by hand: edit the docstrings in {src} and re-run. -->")


