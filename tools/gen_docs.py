# -*- coding: utf-8 -*-
"""
模块文档生成器（gen_docs）
==========================

从源码**自动生成**每个模块同目录的双语文档：``xxx.py`` 对应 ``xxx.zh.md``（中文）
与 ``xxx.en.md``（English）。文档跟着代码走，改 API 时顺手改旁边那篇即可。

语言码用 ISO 639-1 的 ``zh`` / ``en``，与 ``malight.i18n`` 的 ``Language.ZH``、
环境变量 ``MALIGHT_LANG=zh`` 保持一致；将来加繁体就是 ``xxx.zh-TW.md``。

文件命名 / File naming:
    ``path.py`` → ``path.zh.md``（中文）+ ``path.en.md``（English）。
    仓库根的 ``README.md`` 沿用平台约定（GitHub/Gitee 只自动渲染这个名字）保留中文，
    英文入口是 ``README.en.md``。

生成内容 / What each page contains:
    1. 语言开关（中文 / English 互切）+ 返回 README；
    2. 模块摘要（中文取自源码文档字符串，英文另见 tools/body_en.py）；
    3. 类与方法清单，签名直接来自源码，说明取自文档字符串的双语摘要；
    4. 该模块 ``__main__`` 里的完整可运行示例（注释与文案按语言各取一半）；
    5. 同级模块导航。

英文页**不出现中文**（语言开关的 ``[简体中文]`` 除外），``--check`` 会逐行校验。

另外会把 ``README.md`` / ``README.en.md`` 中
``<!-- DOCS-INDEX:START -->`` 与 ``<!-- DOCS-INDEX:END -->`` 之间的索引表重建，
保证 README 与模块列表永不脱节。

用法 / Usage::

    python tools/gen_docs.py              # 生成全部文档
    python tools/gen_docs.py --check      # 只检查（CI 用），有缺漏则退出码 1
    python tools/gen_docs.py path.py      # 只生成名字匹配的模块
"""

