def format_signature(node):
    """把函数签名渲染成一行紧凑文本（不含 self，超长默认值省略）。"""
    args = node.args
    parts, positional = [], list(getattr(args, "posonlyargs", [])) + list(args.args)
    defaults = list(args.defaults)
    pad = len(positional) - len(defaults)
    for i, a in enumerate(positional):
        if a.arg in ("self", "cls"):
            continue
        if i >= pad:
            default = ast.unparse(defaults[i - pad]) if hasattr(ast, "unparse") \
                else "…"
            default = " ".join(str(default).split())
            if len(default) > 14:
                default = default[:11] + "…"
            parts.append("{}={}".format(a.arg, default))
        else:
            parts.append(a.arg)
    if args.vararg:
        parts.append("*" + args.vararg.arg)
    elif args.kwonlyargs:
        parts.append("*")
    for a, d in zip(args.kwonlyargs, args.kw_defaults):
        parts.append(a.arg if d is None else "{}={}".format(a.arg, "…"))
    if args.kwarg:
        parts.append("**" + args.kwarg.arg)
    return "{}({})".format(node.name, ", ".join(parts))


def collect_module(tree):
    """
    从一个模块 AST 里收集顶层函数、类与类方法。

    :return: ``(functions, classes)``，均为按源码顺序排列的列表
    """
    functions, classes = [], []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            functions.append(node)
        elif isinstance(node, ast.ClassDef):
            members, props = [], []
            for sub in node.body:
                if not isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                if sub.name.startswith("_"):
                    continue
                is_prop = any(
                    (isinstance(d, ast.Name) and d.id == "property")
                    or (isinstance(d, ast.Attribute) and d.attr == "setter")
                    for d in sub.decorator_list)
                if is_prop:
                    props.append(sub)
                else:
                    members.append(sub)
            classes.append((node, members, props))
    return functions, classes


def extract_example(src):
    """取出 ``if __name__ == "__main__":`` 之后的示例代码。"""
    marker = 'if __name__ == "__main__":'
    idx = src.find(marker)
    return src[idx:].rstrip() + "\n" if idx >= 0 else ""


