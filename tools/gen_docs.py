def read(path):
    """读文本，原样保留行尾（用于要原样写回的 README）。"""
    return io.open(path, encoding="utf-8", newline="").read()


def read_src(path):
    """读源码并统一成 LF —— 否则源码里的 CRLF 会混进生成的文档。"""
    return (io.open(path, encoding="utf-8", newline="").read()
            .replace("\r\n", "\n").replace("\r", "\n"))


def write(path, text):
    io.open(path, "w", encoding="utf-8", newline="").write(text)


def rel(root, path):
    return os.path.relpath(path, root).replace(os.sep, "/")


#: Markdown 会把 ``<clipPath>`` 这类尖括号当 HTML 标签吞掉，转成行内代码
TAG = re.compile(r"</?[A-Za-z][A-Za-z0-9]*(?:\s+[^<>]*)?>")


def _wrap_tag(m):
    raw = m.string
    if m.start() > 0 and raw[m.start() - 1] == "`" and raw[m.end():m.end() + 1] == "`":
        return m.group(0)                     # 已经是行内代码，别套两层
    return "`" + m.group(0) + "`"


def md_text(text):
    """把文档字符串里的 RST / HTML 记号转成安全的 Markdown。"""
    text = text.replace("``", "`")
    return TAG.sub(_wrap_tag, text)


#: RST 网格表的行分隔线，如 ``=======  ======``
GRID_SEP = re.compile(r"^[ \t]*=+([ \t]+=+)+[ \t]*$")
#: 以 ``::`` 结尾的行 = RST 字面块引导（``示例::``、``用法::``）
LITERAL_HEAD = re.compile(r"^(.*?)::[ \t]*$")


def _dedent(lines):
    """去掉一段文本的公共缩进。"""
    indents = [len(l) - len(l.lstrip()) for l in lines if l.strip()]
    cut = min(indents) if indents else 0
    return [l[cut:] if len(l) >= cut else l.lstrip() for l in lines]


def _trim(lines):
    while lines and not lines[-1].strip():
        lines.pop()
    return lines


def _take_indented(lines, i):
    """从 ``i`` 起吞掉一个「缩进块」（先跳过空行），返回 ``(块内容, 下一个下标)``。"""
    while i < len(lines) and not lines[i].strip():
        i += 1
    block = []
    while i < len(lines) and (not lines[i].strip() or lines[i][:1] in " \t"):
        block.append(lines[i])
        i += 1
    return _trim(block), i


def _take_table(lines, i):
    """从 ``i`` 起吞掉 RST 网格表：连续非空行，遇空行结束。"""
    block = []
    while i < len(lines) and lines[i].strip():
        block.append(lines[i])
        i += 1
    return _trim(block), i


def _split_cells(line):
    """把 RST 网格表的一行按「两个以上空格」切成单元格。"""
    return [c.strip() for c in re.split(r"\s{2,}", line.strip())]


def grid_to_md(block):
    """
    尝试把 RST 网格表转成 Markdown 表格（首行当表头）。

    :return: Markdown 表格文本；形状不规整（列数对不齐）时返回 ``None``
    """
    rows = [_split_cells(l) for l in block if not GRID_SEP.match(l)]
    rows = [r for r in rows if any(r)]
    if len(rows) < 2:
        return None
    ncols = len(rows[0])
    if ncols < 2 or any(len(r) != ncols for r in rows):
        return None
    head, body = rows[0], rows[1:]
    out = ["| " + " | ".join(md_text(c) for c in head) + " |",
           "|" + "---|" * ncols]
    for r in body:
        out.append("| " + " | ".join(md_text(c).replace("|", r"\|") for c in r) + " |")
    return out


def rst_to_md(text):
    """
    把源码文档字符串里的 RST 小记号转成 Markdown 正文。

    处理三件事 / Handles three things:
      * `` ``code`` `` → `` `code` ``；
      * ``示例::`` / ``用法::`` 后面的缩进块 → ```` ```python ```` 代码块；
      * RST 网格表（``====`` 分隔行）→ ```` ```text ```` 等宽块，保住列对齐。
    """
    lines = text.split("\n")
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        head = LITERAL_HEAD.match(line)
        if head and not GRID_SEP.match(line):
            block, nxt = _take_indented(lines, i + 1)
            if block:
                title = md_text(head.group(1)).strip()
                if title:
                    out.append(title)
                    out.append("")
                lang = "python" if ("示例" in title or "用法" in title) else "text"
                out.append("```" + lang)
                out.extend(_dedent(block))
                out.append("```")
                out.append("")
                i = nxt
                continue
        if GRID_SEP.match(line):
            block, nxt = _take_table(lines, i)
            table = grid_to_md(block)
            if table:
                out.extend(table)
                out.append("")
            else:
                out.append("```text")
                out.extend(md_text(l) for l in _dedent(block))
                out.append("```")
                out.append("")
            i = nxt
            continue
        out.append(md_text(line))
        i += 1
    return "\n".join(out)


def split_bilingual(text):
    """
    拆开「中文。 / English.」形式的摘要。

    :return: ``(中文, 英文)``；没有英文部分时第二项为空串
    """
    if "。 / " in text:
        cn, en = text.split("。 / ", 1)
        return cn.strip() + "。", en.strip()
    return text.strip(), ""


#: 摘要里若混进了 ``示例::`` 一类的块引导，从这里截断
EXAMPLE_MARK = re.compile(r"\s*(?:示例|用法|例|Example|Usage|Examples)::")


def first_paragraph(doc):
    """取文档字符串首段（折叠成一行）；遇到 ``::`` 块引导则截断。"""
    if not doc:
        return ""
    head = []
    for line in doc.strip().splitlines():
        s = line.strip()
        if not s or s.endswith("::"):
            break
        head.append(s)
    if not head:
        return ""
    text = " ".join(" ".join(head).split())
    mark = EXAMPLE_MARK.search(text)
    if mark:
        text = text[:mark.start()].strip()
    return text


def module_doc_parts(doc):
    """
    拆解模块文档字符串。

    :return: ``(中文标题, 英文摘要, 中文正文)``
    """
    if not doc:
        return "", "", ""
    lines = [l.rstrip() for l in doc.strip().splitlines()]
    title, english, idx = lines[0].strip(), "", 1
    if "。 / " in title:
        cn_part, english = title.split("。 / ", 1)
        title, english = cn_part + "。", english.strip()
    elif " / " in title:
        title, english = [x.strip() for x in title.split(" / ", 1)]
    elif len(lines) > 1 and len(lines[1].strip()) >= 4 and set(lines[1].strip()) == {"="}:
        idx = 2
        while idx < len(lines) and not lines[idx].strip():
            idx += 1
        if idx < len(lines):
            english = lines[idx].strip()
            idx += 1
    body = "\n".join(lines[idx:]).strip()
    return title, english, body


