def render_api_cn(functions, classes):
    """渲染中文页的 API 清单。"""
    out = []
    if functions:
        out.append("### 函数\n")
        out.append("| 函数 | 说明 |")
        out.append("|---|---|")
        for node in functions:
            cn, _ = split_bilingual(first_paragraph(ast.get_docstring(node)))
            out.append("| `{}` | {} |".format(node.name, md_text(cn).replace("|", r"\|")))
        out.append("")
    for node, members, props in classes:
        cn, _ = split_bilingual(first_paragraph(ast.get_docstring(node)))
        out.append("### `{}`\n".format(node.name))
        if cn:
            out.append(md_text(cn) + "\n")
        rows = []
        for sub in members:
            cn2, _ = split_bilingual(first_paragraph(ast.get_docstring(sub)))
            rows.append(("`{}`".format(format_signature(sub)), cn2))
        for sub in props:
            cn2, _ = split_bilingual(first_paragraph(ast.get_docstring(sub)))
            rows.append(("`{}`（属性）".format(sub.name), cn2))
        if rows:
            out.append("| 方法 | 说明 |")
            out.append("|---|---|")
            for sig, desc in rows:
                out.append("| {} | {} |".format(sig, md_text(desc).replace("|", r"\|")))
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_api_en(functions, classes):
    """
    渲染英文页的 API 清单。

    只输出英文摘要；没有英文时留空（由 ``--check`` 的「英文页纯度」校验兜住），
    绝不回退显示中文 —— 那会让英文读者看到半页中文。
    """
    def en_of(node):
        _cn, en = split_bilingual(first_paragraph(ast.get_docstring(node)))
        return md_text(en)

    out = []
    if functions:
        out.append("### Functions\n")
        out.append("| Function | Description |")
        out.append("|---|---|")
        for node in functions:
            out.append("| `{}` | {} |".format(node.name, en_of(node).replace("|", r"\|")))
        out.append("")
    for node, members, props in classes:
        out.append("### `{}`\n".format(node.name))
        desc = en_of(node)
        if desc:
            out.append(desc + "\n")
        rows = []
        for sub in members:
            rows.append(("`{}`".format(format_signature(sub)), en_of(sub)))
        for sub in props:
            rows.append(("`{}` (property)".format(sub.name), en_of(sub)))
        if rows:
            out.append("| Method | Description |")
            out.append("|---|---|")
            for sig, d in rows:
                out.append("| {} | {} |".format(sig, d.replace("|", r"\|")))
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_page(ctx, lang):
    """:param lang: ``"cn"`` 或 ``"en"``"""
    cn = lang == "cn"
    suffix = ".zh.md" if cn else ".en.md"
    name = ctx["name"]

    head = ["# {}.py".format(name)]
    head.append("")
    switch = ("**简体中文** ｜ [English]({other})" if cn
              else "[简体中文]({other}) ｜ **English**")
    head.append(" ｜ ".join([
        switch.format(other=name + (".en.md" if cn else ".zh.md")),
        "[← 返回 README]({})".format(ctx["readme"]) if cn
        else "[← Back to README]({})".format(ctx["readme_en"]),
    ]))
    head.append("")

    if cn:
        head.append(ctx["title"] or name)
        head.append("")
        if ctx["body"]:
            head.append(ctx["body"])
            head.append("")
    else:
        head.append(ctx["english"] or ctx["title"] or name)
        head.append("")
        if ctx["body_en"]:
            head.append(ctx["body_en"])
            head.append("")

    # 效果预览图（集中在仓库根 assets/images/，由 tools/gen_previews.py 生成；
    # 中英两页共用同一张，所以图里的标签是英文）。
    # 放在模块说明之后、API 清单之前 —— 先让读者看到效果，再看方法列表。
    preview = PREVIEWS.get(ctx["src"])
    if preview:
        head.append("![{}]({})".format(preview[1] if cn else preview[2],
                                       preview_link(ctx["src"], preview[0])))
        head.append("")

    api = render_api_cn(*ctx["api"]) if cn else render_api_en(*ctx["api"])
    head.append("---")
    head.append("")
    head.append("## 类与方法" if cn else "## Classes and methods")
    head.append("")
    head.append(api)

    if ctx["example"]:
        head.append("---")
        head.append("")
        head.append("## 完整示例" if cn else "## Full example")
        head.append("")
        head.append("在 PyCharm 里点绿色三角直接运行，或命令行：`python {}`"
                    if cn else
                    "Run it directly in PyCharm, or from the command line: `python {}`")
        head[-1] = head[-1].format(ctx["src"])
        head.append("")
        head.append("```python")
        head.append(bipair.trim_block(ctx["example"].rstrip(), lang))
        head.append("```")
        head.append("")

    if ctx["siblings"]:
        head.append("---")
        head.append("")
        head.append("## 同级模块" if cn else "## Sibling modules")
        head.append("")
        head.append(" ｜ ".join("[{}]({}{})".format(s, s, suffix)
                               for s in ctx["siblings"]))
        head.append("")

    banner = (BANNER_CN if cn else BANNER_EN).format(src=os.path.basename(ctx["src"]))
    return banner + "\n\n" + "\n".join(head).rstrip() + "\n"


def purity_problems(text):
    """
    英文页里不该出现中文，只有语言开关的 ``[简体中文]`` 例外。

    :return: ``[(行号, 行内容), ...]``
    """
    bad = []
    for no, line in enumerate(text.split("\n"), 1):
        if not CN.search(line) or SWITCH.search(line):
            continue
        bad.append((no, line.strip()[:80]))
    return bad


